@app.post("/api/run")
async def run_pipeline(
    event_log_file: UploadFile = File(...),
    provider: str = Form(...),
    model: str = Form(...),
    base_url: str | None = Form(None),
    api_key: str | None = Form(None),
    temperature: str | None = Form(None),
    max_output_tokens: str | None = Form(None),
    json_retries: str | None = Form("2"),
    use_attributes: bool = Form(False),
    min_support: str | None = Form(None),
    period_enabled: bool = Form(False),
    period_quantity: int | None = Form(1),
    period_unit: str | None = Form("month"),
    cv_threshold: str | None = Form(None),
):
    if not event_log_file.filename.lower().endswith(".xes"):
        raise HTTPException(status_code=400, detail="Please upload a .xes file.")

    min_support_value = float(min_support) if min_support and min_support.strip() else 0.8
    cv_threshold_value = _parse_optional_float(cv_threshold)

    try:
        # Period grouping is mandatory for dashboard execution. Default is 1 month.
        _ = period_enabled  # kept for backward form compatibility
        time_grouper_freq = _build_time_freq(
            period_quantity if period_quantity is not None else 1,
            period_unit if period_unit is not None else "month",
        )
    except ValueError as exc:
        raise HTTPException(status_code=400, detail=str(exc)) from exc
    if cv_threshold_value is None:
        cv_threshold_value = 0.2

    try:
        llm_config = _build_llm_config(
            provider=provider,
            model=model,
            base_url=base_url,
            api_key=api_key,
            temperature=temperature,
            max_output_tokens=max_output_tokens,
            json_retries=json_retries,
        )
    except Exception as exc:
        raise HTTPException(status_code=400, detail=f"Invalid LLM configuration: {exc}") from exc

    try:
        with tempfile.NamedTemporaryFile(suffix=".xes", delete=False) as tmp:
            content = await event_log_file.read()
            tmp.write(content)
            tmp_path = tmp.name

        from Declare4Py.D4PyEventLog import D4PyEventLog

        event_log = D4PyEventLog(case_name="case:concept:name")
        event_log.parse_xes_log(tmp_path)

        run_result, final_report = run_full_pipeline(
            event_log=event_log,
            llm_config=llm_config,
            min_support=min_support_value,
            use_attributes=use_attributes,
            time_grouper_freq=time_grouper_freq,
            cv_threshold=cv_threshold_value,
        )

        return _normalize_result(
            run_result=run_result,
            final_report=final_report,
            time_grouper_freq=time_grouper_freq,
            min_support=min_support_value,
            cv_threshold=cv_threshold_value,
        )
    except HTTPException:
        raise
    except Exception as exc:
        raise HTTPException(status_code=500, detail=f"Pipeline execution failed: {exc}") from exc
    finally:
        try:
            if 'tmp_path' in locals() and os.path.exists(tmp_path):
                os.remove(tmp_path)
        except Exception:
            pass
